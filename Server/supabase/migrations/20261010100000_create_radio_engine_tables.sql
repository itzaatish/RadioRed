-- Objective: Add durable radio sessions, frame delivery history, and atomic lifecycle/claim functions for the engine.
-- Radio orchestration state. Audio generation remains outside this schema.

alter table "public"."frames"
  add column if not exists "status" text not null default 'READY';

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'frames_status_check'
  ) then
    alter table "public"."frames"
      add constraint "frames_status_check"
      check ("status" in ('GENERATING', 'READY', 'FAILED'));
  end if;
end $$;

create table if not exists "public"."radio_sessions" (
  "id" uuid primary key default gen_random_uuid(),
  "tone" integer not null,
  "status" text not null default 'ACTIVE'
    check ("status" in ('ACTIVE', 'PAUSED', 'STOPPED', 'EXPIRED')),
  "session_version" bigint not null default 1 check ("session_version" > 0),
  "last_seen" timestamptz not null default now(),
  "playback_started_at" timestamptz,
  "current_frame_id" bigint references "public"."frames"("id"),
  "stop_reason" text,
  "stopped_at" timestamptz,
  "created_at" timestamptz not null default now(),
  "updated_at" timestamptz not null default now()
);

-- Aatish FM currently has one private listener. This also makes concurrent
-- start requests safe across multiple Node processes.
create unique index if not exists "radio_sessions_one_active_idx"
  on "public"."radio_sessions" ((true)) where "status" = 'ACTIVE';
create index if not exists "radio_sessions_status_last_seen_idx"
  on "public"."radio_sessions" ("status", "last_seen");

alter table "public"."radio_sessions" enable row level security;

create table if not exists "public"."radio_session_frames" (
  "id" bigint generated by default as identity primary key,
  "session_id" uuid not null references "public"."radio_sessions"("id"),
  "frame_id" bigint not null references "public"."frames"("id"),
  "session_version" bigint not null,
  "sequence_number" integer not null check ("sequence_number" > 0),
  "status" text not null check ("status" in ('READY', 'DELIVERED', 'PLAYING', 'PLAYED', 'FAILED')),
  "delivery_key" text,
  "delivered_at" timestamptz,
  "playback_started_at" timestamptz,
  "playback_completed_at" timestamptz,
  "created_at" timestamptz not null default now(),
  unique ("session_id", "sequence_number"),
  unique ("session_id", "frame_id")
);

create unique index if not exists "radio_session_frames_delivery_key_idx"
  on "public"."radio_session_frames" ("session_id", "session_version", "delivery_key")
  where "delivery_key" is not null;
create index if not exists "radio_session_frames_lookup_idx"
  on "public"."radio_session_frames" ("session_id", "session_version", "status", "sequence_number");

alter table "public"."radio_session_frames" enable row level security;

create or replace function "public"."stop_radio_session"(
  p_session_id uuid,
  p_status text,
  p_reason text default null
)
returns "public"."radio_sessions"
language plpgsql
as $$
declare
  v_session "public"."radio_sessions"%rowtype;
begin
  if p_status not in ('PAUSED', 'STOPPED', 'EXPIRED') then
    raise exception 'Invalid inactive session status: %', p_status;
  end if;

  update "public"."radio_sessions"
     set "status" = p_status,
         "session_version" = "session_version" + 1,
         "stop_reason" = p_reason,
         "stopped_at" = now(),
         "updated_at" = now()
   where "id" = p_session_id
     and (
       "status" = 'ACTIVE'
       or (p_status = 'STOPPED' and "status" = 'PAUSED')
     )
   returning * into v_session;

  if not found then
    select * into v_session from "public"."radio_sessions" where "id" = p_session_id;
  end if;

  return v_session;
end;
$$;

create or replace function "public"."activate_radio_session"(
  p_session_id uuid,
  p_tone integer
)
returns "public"."radio_sessions"
language plpgsql
as $$
declare
  v_session "public"."radio_sessions"%rowtype;
begin
  update "public"."radio_sessions"
     set "tone" = p_tone,
         "status" = 'ACTIVE',
         "session_version" = "session_version" + 1,
         "last_seen" = now(),
         "playback_started_at" = null,
         "current_frame_id" = null,
         "stop_reason" = null,
         "stopped_at" = null,
         "updated_at" = now()
   where "id" = p_session_id and "status" <> 'ACTIVE'
   returning * into v_session;

  if not found then
    select * into v_session from "public"."radio_sessions" where "id" = p_session_id;
  end if;

  return v_session;
end;
$$;

-- This function serializes all claims by locking the session row. It returns
-- an already delivered frame for retry safety, reserves a READY frame for the
-- scheduler, and otherwise claims exactly one eligible generated frame.
create or replace function "public"."claim_radio_frame"(
  p_session_id uuid,
  p_expected_version bigint,
  p_deliver boolean,
  p_delivery_key text default null,
  p_max_pending integer default 1
)
returns table (
  frame_id bigint,
  external_id text,
  audio_path text,
  duration_seconds integer,
  transcript text,
  metadata jsonb,
  sequence_number integer,
  delivery_status text,
  session_version bigint
)
language plpgsql
as $$
declare
  v_session "public"."radio_sessions"%rowtype;
  v_existing "public"."radio_session_frames"%rowtype;
  v_frame "public"."frames"%rowtype;
  v_previous_frame_id bigint;
  v_next_frame_id bigint;
  v_sequence integer;
  v_status text;
  v_ready_count integer;
begin
  if p_max_pending < 1 then
    raise exception 'p_max_pending must be at least 1';
  end if;

  select * into v_session
    from "public"."radio_sessions"
   where "id" = p_session_id
   for update;

  if not found or v_session."status" <> 'ACTIVE' or v_session."session_version" <> p_expected_version then
    return;
  end if;

  if p_deliver and p_delivery_key is not null then
    select * into v_existing
      from "public"."radio_session_frames"
     where "session_id" = p_session_id
       and "session_version" = p_expected_version
       and "delivery_key" = p_delivery_key
     limit 1;

    if found then
      select * into v_frame from "public"."frames" where "id" = v_existing."frame_id";
      return query select v_frame."id", v_frame."external_id", v_frame."audio_path",
        v_frame."duration_seconds", v_frame."transcript", v_frame."metadata",
        v_existing."sequence_number", v_existing."status", v_existing."session_version";
      return;
    end if;
  end if;

  if p_deliver then
    -- An unacknowledged delivery is returned again instead of silently
    -- skipping it when a browser retries a request.
    select * into v_existing
      from "public"."radio_session_frames"
     where "session_id" = p_session_id
       and "session_version" = p_expected_version
       and "status" = 'DELIVERED'
     order by "sequence_number" asc
     limit 1
     for update;

    if found then
      if p_delivery_key is not null then
        update "public"."radio_session_frames"
           set "delivery_key" = p_delivery_key
         where "id" = v_existing."id";
        v_existing."delivery_key" := p_delivery_key;
      end if;
      select * into v_frame from "public"."frames" where "id" = v_existing."frame_id";
      return query select v_frame."id", v_frame."external_id", v_frame."audio_path",
        v_frame."duration_seconds", v_frame."transcript", v_frame."metadata",
        v_existing."sequence_number", v_existing."status", v_existing."session_version";
      return;
    end if;

    select * into v_existing
      from "public"."radio_session_frames"
     where "session_id" = p_session_id
       and "session_version" = p_expected_version
       and "status" = 'READY'
     order by "sequence_number" asc
     limit 1
     for update;

    if found then
      update "public"."radio_session_frames"
         set "status" = 'DELIVERED',
             "delivered_at" = now(),
             "delivery_key" = p_delivery_key
       where "id" = v_existing."id";
      v_existing."status" := 'DELIVERED';
      select * into v_frame from "public"."frames" where "id" = v_existing."frame_id";
      return query select v_frame."id", v_frame."external_id", v_frame."audio_path",
        v_frame."duration_seconds", v_frame."transcript", v_frame."metadata",
        v_existing."sequence_number", v_existing."status", v_existing."session_version";
      return;
    end if;
  else
    select count(*) into v_ready_count
      from "public"."radio_session_frames"
     where "session_id" = p_session_id
       and "session_version" = p_expected_version
       and "status" = 'READY';

    if v_ready_count >= p_max_pending then
      select * into v_existing
        from "public"."radio_session_frames"
       where "session_id" = p_session_id
         and "session_version" = p_expected_version
         and "status" = 'READY'
       order by "sequence_number" asc
       limit 1;

      if found then
        select * into v_frame from "public"."frames" where "id" = v_existing."frame_id";
        return query select v_frame."id", v_frame."external_id", v_frame."audio_path",
          v_frame."duration_seconds", v_frame."transcript", v_frame."metadata",
          v_existing."sequence_number", v_existing."status", v_existing."session_version";
        return;
      end if;
    end if;
  end if;

  select "frame_id" into v_previous_frame_id
    from "public"."radio_session_frames"
   where "session_id" = p_session_id
     and "session_version" = p_expected_version
   order by "sequence_number" desc
   limit 1;

  if v_previous_frame_id is not null then
    select "next_frame_id" into v_next_frame_id
      from "public"."frames"
     where "id" = v_previous_frame_id;

    if v_next_frame_id is not null then
      select * into v_frame
        from "public"."frames"
       where "id" = v_next_frame_id and "status" = 'READY';
      -- A linked successor exists but generation has not finished yet. Do not
      -- jump ahead to another sentence and break the stored ordering.
      if not found then
        return;
      end if;
    end if;
  end if;

  if v_frame."id" is null then
    select f.* into v_frame
      from "public"."sentences" s
      join "public"."frames" f on f."id" = s."first_frame_id"
     where s."tone" = v_session."tone"
       and f."status" = 'READY'
       and not exists (
         select 1 from "public"."radio_session_frames" sf
          where sf."session_id" = p_session_id and sf."frame_id" = f."id"
       )
     order by s."created_at" asc, s."id" asc
     limit 1;
  end if;

  if v_frame."id" is null then
    return;
  end if;

  select coalesce(max("sequence_number"), 0) + 1 into v_sequence
    from "public"."radio_session_frames"
   where "session_id" = p_session_id;

  v_status := case when p_deliver then 'DELIVERED' else 'READY' end;
  insert into "public"."radio_session_frames" (
    "session_id", "frame_id", "session_version", "sequence_number", "status", "delivery_key", "delivered_at"
  ) values (
    p_session_id, v_frame."id", p_expected_version, v_sequence, v_status,
    case when p_deliver then p_delivery_key else null end,
    case when p_deliver then now() else null end
  );

  update "public"."radio_sessions"
     set "current_frame_id" = v_frame."id", "updated_at" = now()
   where "id" = p_session_id and "session_version" = p_expected_version and "status" = 'ACTIVE';

  return query select v_frame."id", v_frame."external_id", v_frame."audio_path",
    v_frame."duration_seconds", v_frame."transcript", v_frame."metadata",
    v_sequence, v_status, p_expected_version;
end;
$$;
