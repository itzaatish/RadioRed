// Objective: Generate a safe Supabase migration from a declarative table schema definition.
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const SUPABASE_DIR = path.join(ROOT, "supabase");
const MIGRATIONS_DIR = path.join(SUPABASE_DIR, "migrations");
const IDENTIFIER = /^[a-z][a-z0-9_]{0,62}$/;
const SQL_TYPES = /^(bigint|integer|smallint|text|boolean|uuid|jsonb|date|time|timestamptz|numeric(?:\(\d{1,4},\d{1,4}\))?)$/;

function fail(message) {
  throw new Error(message);
}

function identifier(value, label = "identifier") {
  if (typeof value !== "string" || !IDENTIFIER.test(value)) fail(`Invalid ${label}: ${value}`);
  return `"${value}"`;
}

function argument(name) {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
}

function defaultExpression(value) {
  if (value === undefined) return "";
  if (typeof value === "boolean" || typeof value === "number") return ` default ${value}`;
  if (typeof value !== "string") fail("default must be a string, number, or boolean");
  if (["now()", "gen_random_uuid()", "true", "false"].includes(value)) return ` default ${value}`;
  if (/^'[^']*'$/.test(value)) return ` default ${value}`;
  fail(`Unsupported default expression: ${value}`);
}

function tableSql(definition) {
  if (!definition || typeof definition !== "object") fail("The table definition must be a JSON object.");
  const schemaName = definition.schema || "public";
  const tableName = definition.table;
  if (!Array.isArray(definition.columns) || definition.columns.length === 0) fail("columns must contain at least one column.");

  const schema = identifier(schemaName, "schema");
  const table = identifier(tableName, "table");
  const columnSql = definition.columns.map((column) => {
    const name = identifier(column.name, "column name");
    if (typeof column.type !== "string" || !SQL_TYPES.test(column.type)) {
      fail(`Unsupported type for ${column.name}: ${column.type}`);
    }
    if (column.identity && !["bigint", "integer", "smallint"].includes(column.type)) {
      fail(`identity is only valid for integer columns (${column.name})`);
    }
    let sql = `${name} ${column.type}`;
    if (column.identity) sql += " generated by default as identity";
    if (column.primaryKey) sql += " primary key";
    if (column.notNull) sql += " not null";
    if (column.unique) sql += " unique";
    sql += defaultExpression(column.default);
    if (column.references) {
      const reference = column.references;
      const targetSchema = identifier(reference.schema || schemaName, "reference schema");
      const targetTable = identifier(reference.table, "reference table");
      const targetColumn = identifier(reference.column || "id", "reference column");
      const action = reference.onDelete ? String(reference.onDelete).toLowerCase() : "";
      if (action && !["cascade", "restrict", "set null", "set default", "no action"].includes(action)) {
        fail(`Unsupported onDelete action for ${column.name}`);
      }
      sql += ` references ${targetSchema}.${targetTable}(${targetColumn})${action ? ` on delete ${action}` : ""}`;
    }
    return sql;
  });

  const statements = [];
  if (schemaName !== "public" && definition.createSchema === true) {
    statements.push(`create schema if not exists ${schema};`);
  }
  statements.push(`create table if not exists ${schema}.${table} (\n  ${columnSql.join(",\n  ")}\n);`);
  for (const index of definition.indexes || []) {
    if (!Array.isArray(index.columns) || index.columns.length === 0) fail("Each index needs columns.");
    const name = index.name || `${tableName}_${index.columns.join("_")}_idx`;
    statements.push(
      `create ${index.unique ? "unique " : ""}index if not exists ${identifier(name, "index name")} on ${schema}.${table} (${index.columns.map((column) => identifier(column, "index column")).join(", ")});`,
    );
  }
  if (definition.rls !== false) statements.push(`alter table ${schema}.${table} enable row level security;`);
  return `${statements.join("\n\n")}\n`;
}

function main() {
  const definitionPath = argument("definition");
  if (!definitionPath) fail("Usage: npm run db:make-table -- --definition database/table.schema.example.json");
  if (!fs.existsSync(path.join(SUPABASE_DIR, "config.toml"))) {
    fail("Supabase is not initialized. Run: npm run supabase -- init");
  }

  const definition = JSON.parse(fs.readFileSync(path.resolve(process.cwd(), definitionPath), "utf8"));
  const name = argument("name") || `create_${definition.schema || "public"}_${definition.table}`;
  if (!IDENTIFIER.test(name)) fail("Migration name must be lowercase snake_case.");
  fs.mkdirSync(MIGRATIONS_DIR, { recursive: true });
  const before = new Set(fs.readdirSync(MIGRATIONS_DIR));
  const command = process.platform === "win32" ? "npx.cmd" : "npx";
  const result = spawnSync(command, ["supabase", "migration", "new", name], { cwd: ROOT, stdio: "inherit" });
  if (result.status !== 0) process.exit(result.status || 1);

  const created = fs.readdirSync(MIGRATIONS_DIR).find((file) => !before.has(file) && file.endsWith(".sql"));
  if (!created) fail("Supabase CLI did not create a migration file.");
  const migrationPath = path.join(MIGRATIONS_DIR, created);
  fs.writeFileSync(migrationPath, tableSql(definition), "utf8");
  console.log(`Created ${path.relative(ROOT, migrationPath)}`);
}

main();
